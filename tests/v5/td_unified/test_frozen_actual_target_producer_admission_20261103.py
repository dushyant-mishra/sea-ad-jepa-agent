def require(condition: bool, reason: str) -> None:
    if not condition:
        raise AssertionError("ACTUAL_TARGET_PRODUCER_ADMISSION_REFUSED: " + reason)


def pinned(root: Path, sha: str) -> None:
    actual = subprocess.check_output(
        ["git", "rev-parse", "HEAD"], cwd=root, text=True
    ).strip()
    require(actual == sha, "exact source head drift: " + str(root))


def run(
    *, fit_payload: Path, source_root: Path, pr534_root: Path,
    r5_root: Path, relational_root: Path, tournament_root: Path,
    design_root: Path, report: Path,
) -> dict:
    for root, sha in (
        (source_root, SOURCE_SHA),
        (pr534_root, PR534_SHA),
        (r5_root, PR526_SHA),
        (relational_root, PR316_SHA),
        (tournament_root, PR313_SHA),
        (design_root, PR338_SHA),
    ):
        pinned(root, sha)
    raw = json.loads(fit_payload.read_text(encoding="utf-8"))
    require(raw.get("schema") == "PR328_FROZEN_FIT_ONLY_TO_CASEBUNDLE_ADMISSION_V1",
            "not original PR534 fit-only transport")
    require(raw.get("frozen_generator_head") == SOURCE_SHA
            and raw.get("world_sha256") == WORLD_SHA
            and raw.get("fit_view_sha256") == FIT_SHA,
            "wrong frozen world/fit SHA")
    require(raw.get("authority") == OFF, "synthetic transport acquired authority")
    cells = raw.get("cells")
    require(type(cells) is list and len(cells) == 30
            and raw.get("n_original_cells") == 480
            and raw.get("n_original_addresses") == 48,
            "unexpected frozen fit-only geometry")
    require(len({c["cell_id"] for c in cells}) == len(cells), "cell identity collision")
    require(all(c["split"] == "train" for c in cells), "original train split only")
    counts = np.asarray([c["counts"] for c in cells], dtype=np.int64)
    support = np.asarray([c["support"] for c in cells], dtype=np.bool_)
    require(counts.shape == support.shape == (30, 48), "source array geometry drift")
    require(bool(np.all(counts >= 0)) and bool(np.all(counts[~support] == 0)),
            "raw counts/support invalid")
    require(len({c["source_id"] for c in cells}) == 3, "source strata changed")
    require(len({c["donor_id"] for c in cells}) >= 3, "donor structure changed")

    # Use PR526's ACTUAL existing measured-target construction code, not
    # a newly defined C3 target or fitted surrogate.
    sys.path.insert(0, str(r5_root))
    from scripts.v79.audit_frozen_measured_panel_observability_v1 import (
        measured_panel_target, QUERY_INDEX, OTHER_GENE_PANEL
    )
    require(QUERY_INDEX == 0 and OTHER_GENE_PANEL == tuple(range(1, 9)),
            "historical R5-shape target indices changed")
    eligible, teacher_target = measured_panel_target(counts, support)
    changed = counts.copy()
    changed[:, 0] += 10000
    eligible_q, target_q = measured_panel_target(changed, support)
    require(np.array_equal(eligible, eligible_q)
            and np.array_equal(teacher_target, target_q, equal_nan=True),
            "q scalar leaked into measured teacher target")
    require(bool(np.isfinite(teacher_target[eligible]).all())
            and bool(np.isnan(teacher_target[~eligible]).all()),
            "NOT_ESTIMABLE was converted to a measurement")
    require(bool(eligible.any()), "no measured C3 target in original 30-row subset")

    by_source = {}
    for source in sorted({c["source_id"] for c in cells}):
        rows = [i for i, c in enumerate(cells) if c["source_id"] == source]
        by_source[source] = {
            "sampled_fit_rows": len(rows),
            "measured_target_rows": int(eligible[rows].sum()),
            "not_estimable_rows": int((~eligible[rows]).sum()),
        }

    # Actual relational TD gate sees original PR328 split into strictly
    # disjoint Z/X/Y 16-gene views.  Never fabricate the required 512-gene
    # measurements or repeat one gene to make the source appear compatible.
    sys.path.insert(0, str(relational_root / "scripts" / "v5"))
    import td_relational_successor_observed_executor_v2 as X
    import td_relational_successor_geometry_v1 as M
    require(M.VIEW_FEATURE_COUNT == 512 and M.PAIR_WIDTH == 2048,
            "PR316 relational contract drift")
    require(counts.shape[1] < 3 * M.VIEW_FEATURE_COUNT,
            "PR328 no longer smaller than frozen relational geometry")
    kwargs = {
        "source": "PR328_SYNTHETIC_NOT_REAL",
        "panel_id": "UNCHANGED_FROZEN_48_ADDRESS_SOURCE",
        "z_values": counts[:, :16],
        "x_values": counts[:, 16:32],
        "y_values": counts[:, 32:48],
        "z_measured": support[:, :16],
        "x_measured": support[:, 16:32],
        "y_measured": support[:, 32:48],
        "z_feature_ids": [f"SYNTH_ADDR_{j:04d}" for j in range(16)],
        "x_feature_ids": [f"SYNTH_ADDR_{j:04d}" for j in range(16, 32)],
        "y_feature_ids": [f"SYNTH_ADDR_{j:04d}" for j in range(32, 48)],
        "donor_ids": [c["donor_id"] for c in cells],
        "operator_ids": [c["operator_id"] for c in cells],
        "global_rows": list(range(len(cells))),
        "source_library": counts.sum(axis=1).astype(float),
        "detected_genes": (counts > 0).sum(axis=1).astype(np.int64),
        "focal_mask": np.ones(len(cells), dtype=bool),
        "neighbor_pool_mask": np.ones(len(cells), dtype=bool),
        "min_focal_anchors_per_donor": 1,
    }
    try:
        X.evaluate_observed_relational_profile(**kwargs)
    except X.ObservedExecutorError as exc:
        require("exactly 512 features" in str(exc),
                "C2 gate refused for an unexpected reason: " + str(exc))
    else:
        raise AssertionError("C2 gate accepted scientifically incompatible 48-feature source")

    # Actual PR313 C3 candidate adapter requires a student prediction. It
    # must NOT invent one using the measured teacher target itself. Passing
    # an actual measured target alone must produce no C3 qualification.
    sys.path.insert(0, str(tournament_root / "scripts" / "v5"))
    import td_real_tournament_case_ledger_v1 as L
    import td_real_candidate_adapters_v1 as A
    eligible_cells = [c for i, c in enumerate(cells) if eligible[i]]
    rows = [
        {
            "cell_id": c["cell_id"], "donor_id": c["donor_id"],
            "source": c["source_id"], "operator": c["operator_id"],
            "split": "TRAIN", "support_state": "MEASURED_POSITIVE",
            "query_id": "PR328_SYNTH_ADDR_0000",
        }
        for c in eligible_cells
    ]
    ledger = L.build_case_ledger(rows)
    measured_observations = {
        c["cell_id"]: {"query_target": teacher_target[i].tolist()}
        for i, c in enumerate(cells) if eligible[i]
    }
    try:
        A.build_candidate_payload(
            "C3_QUERY_MEASURED", ledger, measured_observations
        )
    except A.CandidateAdapterError as exc:
        require("query_student" in str(exc),
                "C3 adapter refused for unexpected reason: " + str(exc))
    else:
        raise AssertionError("C3 adapter fabricated a student prediction")
    # Do not bypass the failure by copying measured query_target into
    # query_student. No learned estimator was fitted or scored here.

    status_path = design_root / "results" / "target_discovery" / "TD_REAL_GATE_DESIGN_READINESS_V2.json"
    design = json.loads(status_path.read_text(encoding="utf-8"))
    require(design["counts"]["blocked_prospective_rule_required"] == 13
            and design["real_td_authorized"] is False
            and design["target_selection_authorized"] is False,
            "real gate design authorization changed")
    out = {
        "schema": "JEPA_ACTUAL_C2_C3_PRODUCER_ADMISSION_READONLY_V1",
        "status": "C3_MEASURED_TARGET_CONSTRUCTED__C2_GEOMETRY_INCOMPATIBLE__C3_STUDENT_ABSENT__REAL_GATE_BLOCKED",
        "source_pr328_world_sha256": WORLD_SHA,
        "source_pr328_fit_sha256": FIT_SHA,
        "source_original_cells": 480,
        "source_original_addresses": 48,
        "n_fit_only_sampled_cells": len(cells),
        "n_fit_only_donors": len({c["donor_id"] for c in cells}),
        "c3_measured_targets": int(eligible.sum()),
        "c3_not_estimable": int((~eligible).sum()),
        "c3_query_scalar_invariant": True,
        "c3_target_producer": "EXISTING_PR526_MEASURED_Q_OTHER_8_DIAGNOSTIC",
        "c3_estimator_fitted": False,
        "c3_actual_candidate_adapter": "PR313_REQUIRES_QUERY_STUDENT__REFUSED",
        "c2_actual_gate": "PR316_THREE_DISJOINT_512_FEATURE_VIEWS__REFUSED_SOURCE_48",
        "c2_no_padding_no_repeated_features": True,
        "blocked_real_gate_rules": 13,
        "source_specific": by_source,
        "controllers_truth_opened": False,
        "known_truth_decisions_scored": False,
        "human_support_semantics_qualified": False,
        "source_authentication": False,
        "training_performed": False,
        "authority": dict(OFF),
    }
    report.parent.mkdir(parents=True, exist_ok=True)
    report.write_text(json.dumps(out, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    return out


def main():
    parser = argparse.ArgumentParser()
    for arg in ("fit_payload", "source_root", "pr534_root", "r5_root",
                "relational_root", "tournament_root", "design_root", "report"):
        parser.add_argument("--" + arg.replace("_", "-"), type=Path, required=True)
    args = parser.parse_args()
    result = run(**vars(args))
    print(json.dumps(result, sort_keys=True))


if __name__ == "__main__":
    main()
