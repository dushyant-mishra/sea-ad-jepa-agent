def _registry(tmp, studies, drop_exposure=None, drop_study=None):
    e = {}
    for s in studies:
        if s == drop_study:
            continue
        e[s] = {"etl_status": "X", "outcome_exposure": "" if s == drop_exposure
                else "INSPECTED_DEVELOPMENT", "biological_estimability": "Y",
                "source_reference": "t", "reviewer": "t", "asserted_on": "2026-09-25"}
    p = os.path.join(tmp, "reg.json")
    with open(p, "w") as fh:
        json.dump({"registry_id": "T", "assertions": e}, fh)
    return p


