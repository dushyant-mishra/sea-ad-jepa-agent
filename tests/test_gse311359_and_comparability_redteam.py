# 3 genes + 3 guides (1 target x 2 elements, 1 non-targeting)
BASE_FEATURES = [
    ("ENSG0001", "GENEA", "Gene Expression"),
    ("ENSG0002", "GENEB", "Gene Expression"),
    ("ENSG0003", "GENEC", "Gene Expression"),
    ("TGT_enh_1", "TGT", "CRISPR Guide Capture"),
    ("TGT_enh_2", "TGT", "CRISPR Guide Capture"),      # shares display name
    ("non-targeting_00000", "non-targeting_00000", "CRISPR Guide Capture"),
]
N_CELLS = 6


def write_gz_lines(path, lines):
    with gzip.open(path, "wt", newline="") as fh:
        for l in lines:
            fh.write(l + "\n")


def build_sample(d, s, features, entries, n_cells=N_CELLS):
    """entries: list of (feature_row_1based, cell_1based, value)"""
    pref = os.path.join(d, "%s_%s" % (GSM[s], s))
    write_gz_lines(pref + "_barcodes.tsv.gz",
                   ["CELL%03d-1" % i for i in range(n_cells)])
    write_gz_lines(pref + "_features.tsv.gz",
                   ["\t".join(f) for f in features])
    body = ["%%MatrixMarket matrix coordinate integer general",
            "%%generated by test fixture",
            "%d %d %d" % (len(features), n_cells, len(entries))]
    body += ["%d %d %d" % e for e in entries]
    write_gz_lines(pref + "_matrix.mtx.gz", body)


def healthy_entries():
    """Each guide dominates its own cells; every guide also carries gene counts."""
    e = []
    # cells 1,2 -> TGT_enh_1 (row 4); cells 3,4 -> TGT_enh_2 (row 5);
    # cells 5,6 -> non-targeting (row 6)
    for cell, grow in ((1, 4), (2, 4), (3, 5), (4, 5), (5, 6), (6, 6)):
        e.append((grow, cell, 50))               # dominant guide UMI
        for gene_row in (1, 2, 3):
            e.append((gene_row, cell, 20 + gene_row + cell))
    return e


def build_store(tmp, features=None, entries=None, samples=None):
    d = os.path.join(tmp, "extract")
    os.makedirs(d, exist_ok=True)
    for s in (samples or SAMPLES):
        build_sample(d, s, features or BASE_FEATURES, entries or healthy_entries())
    return d


def run311(extract_dir, out_dir):
    return subprocess.run(
        [sys.executable, GSE311359, "--extract-dir", extract_dir,
         "--out-dir", out_dir], capture_output=True, text=True).returncode


