"""Adversarial suites for the GSE311359 ID-keyed producer and comparability v2.

Every fixture must make the producer exit NONZERO, asserted on exit status
rather than message text. Each suite opens with a positive control, because a
rejection is only meaningful if the healthy case passes.

Fixtures are synthetic 10x-format triples (barcodes / features / matrix.mtx.gz)
and synthetic registries, built in temp directories. Nothing touches the
authenticated store or any committed evidence.

The load-bearing case is `test_phantom_unit_signature_rejected`: it plants the
exact V1 defect — a guide feature that acquires cells while contributing zero
counts — and requires the producer to refuse. That defect shipped silently once;
this is the test that would have caught it.
"""

