def test_colliding_display_names_do_not_collapse():
    """Positive behavioural check: two guides sharing a name stay separate."""
    with tempfile.TemporaryDirectory() as tmp:
        out = os.path.join(tmp, "out")
        assert run311(build_store(tmp), out) == 0
        with open(os.path.join(out, "GSE311359_ID_KEYED_RECEIPT_V2.json")) as fh:
            rec = json.load(fh)
        assert rec["display_name_collisions"] == {"TGT": ["TGT_enh_1", "TGT_enh_2"]}
        assert rec["phantom_units_detected"] == 0
        # 2 target elements + 1 control, across 7 samples
        assert rec["units_with_cells"] == 21
        assert rec["perturbed_units"] == 14 and rec["nt_units"] == 7


