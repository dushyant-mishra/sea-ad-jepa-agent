def test_nnz_header_mismatch_rejected():
    """Declared nnz disagrees with the number of entries actually present."""
    with tempfile.TemporaryDirectory() as tmp:
        d = os.path.join(tmp, "extract")
        os.makedirs(d, exist_ok=True)
        for s in SAMPLES:
            build_sample(d, s, BASE_FEATURES, healthy_entries())
        # corrupt one sample's header count
        pref = os.path.join(d, "%s_%s" % (GSM["S2"], "S2"))
        with gzip.open(pref + "_matrix.mtx.gz", "rt") as fh:
            lines = fh.read().splitlines()
        hdr = lines[2].split()
        lines[2] = "%s %s %d" % (hdr[0], hdr[1], int(hdr[2]) + 7)
        write_gz_lines(pref + "_matrix.mtx.gz", lines)
        assert run311(d, os.path.join(tmp, "out")) != 0


