def test_positive_control_healthy_fixture_exits_zero():
    with tempfile.TemporaryDirectory() as tmp:
        assert run311(build_store(tmp), os.path.join(tmp, "out")) == 0


def test_phantom_unit_signature_rejected():
    """THE V1 DEFECT: a guide acquires cells but contributes zero gene counts."""
    with tempfile.TemporaryDirectory() as tmp:
        e = []
        for cell, grow in ((1, 4), (2, 4), (3, 5), (4, 5), (5, 6), (6, 6)):
            e.append((grow, cell, 50))
        # gene counts ONLY for cells assigned to enh_1 and the control;
        # cells 3 and 4 (enh_2) get none -> that unit reports cells, zero counts
        for cell in (1, 2, 5, 6):
            for gene_row in (1, 2, 3):
                e.append((gene_row, cell, 30))
        assert run311(build_store(tmp, entries=e), os.path.join(tmp, "out")) != 0


