def test_feature_row_order_swap_rejected():
    """Same feature set, permuted order: pooling across samples becomes unsafe."""
    with tempfile.TemporaryDirectory() as tmp:
        d = os.path.join(tmp, "extract")
        os.makedirs(d, exist_ok=True)
        for s in SAMPLES:
            f = list(BASE_FEATURES)
