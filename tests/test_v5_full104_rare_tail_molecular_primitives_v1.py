def test_tail_triplet_sampling_respects_q95_and_64_cap() -> None:
    n = 100
    rows = np.arange(1000, 1000 + n)
    # Simple finite distance geometry with every anchor's ranking determined by
    # absolute local-index separation.
    ix = np.arange(n)
    d = np.abs(ix[:, None] - ix[None, :]).astype(float)
    triplets = P.select_tail_triplets(
        z_distance=d,
        selection_rows=rows,
        panel=0,
        source_code=1,
        fold_index=2,
        donor_code=7,
        operator_code=35,
    )
    assert len(triplets) <= 64
    assert len(set(triplets)) == len(triplets)
    for i, j, k in triplets:
        assert i != j and i != k and j != k
        assert rows[j] < rows[k]


def test_matching_blocks_cover_rows_once_and_avoid_terminal_singleton() -> None:
    n = 17
    rows = np.arange(100, 100 + n)
    library = np.linspace(1000, 2000, n)
    detected = np.linspace(200, 500, n)[::-1]
    blocks = P.build_depth_detection_blocks(
        selection_rows=rows,
        source_library=library,
        detected_count=detected,
    )
    flat = np.concatenate(blocks)
    assert sorted(flat.tolist()) == list(range(n))
    assert len(np.unique(flat)) == n
    # Historical rule merges a one-element final chunk into the prior chunk.
    assert all(len(b) != 1 for b in blocks)


