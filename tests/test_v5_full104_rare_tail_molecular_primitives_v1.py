def test_distance_matrix_matches_tie_aware_sign_concordance() -> None:
    # Pad to 2048 coordinates so the frozen >=256-informative gate is satisfied.
    a = np.zeros((3, 2048), dtype=np.int8)
    a[0, :4] = [1, 1, -1, 0]
    a[1, :4] = [1, -1, -1, 0]
    a[2, :4] = [0, 0, 0, 0]
    # Make coordinates 4..259 jointly informative and identical.
    a[0, 4:260] = 1
    a[1, 4:260] = 1
    a[2, 4:260] = 1

    d = P.distance_matrix(a)
    assert d.shape == (3, 3)
    # Pair 0/1 differs only at coordinate 1 among 259 informative coords:
    # sign difference magnitude 2 -> divided by 2 => one discordant unit.
    assert d[0, 1] == pytest.approx(1 / 259)
    assert np.allclose(d, d.T, equal_nan=True)
    assert np.allclose(np.diag(d), 0.0)


def test_nearest_half_uses_distance_then_selection_row_tiebreak() -> None:
    d = np.array(
        [
            [0.0, 0.2, 0.2, 0.3, 0.4],
            [0.2, 0.0, 0.1, 0.1, 0.5],
            [0.2, 0.1, 0.0, 0.2, 0.5],
            [0.3, 0.1, 0.2, 0.0, 0.5],
            [0.4, 0.5, 0.5, 0.5, 0.0],
        ]
    )
    rows = np.array([100, 30, 20, 40, 50])
    # Anchor0 has four candidates; nearest half keeps 2. Distance tie 1/2 is
    # broken by selection_row, so local index 2 (row20) precedes 1 (row30).
    got = P.nearest_half_candidates(d, anchor=0, selection_rows=rows)
    assert got.tolist() == [2, 1]


def test_isolation_score_is_furthest_member_inside_nearest_half() -> None:
    d = np.array(
        [
            [0.0, 0.1, 0.2, 0.4],
            [0.1, 0.0, 0.3, 0.5],
            [0.2, 0.3, 0.0, 0.6],
            [0.4, 0.5, 0.6, 0.0],
        ]
    )
    rows = np.array([10, 20, 30, 40])
    scores, candidates = P.isolation_scores_and_candidates(d, rows)
    # Three finite others -> ceil(3/2)=2.
    assert candidates[0].tolist() == [1, 2]
    assert scores[0] == pytest.approx(0.2)


