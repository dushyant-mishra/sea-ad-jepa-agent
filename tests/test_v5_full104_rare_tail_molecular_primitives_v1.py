def test_gene_and_pair_hash_serialization_is_little_endian_int32(monkeypatch) -> None:
    # Synthetic 10k-address common set; patch expected hashes to the exact
    # little-endian int32 serialization generated by the frozen slices.
    common = np.arange(10_000, dtype=np.int64)
    ranked = P.ranked_common(common)
    expected_gene = {}
    expected_pair = {}
    for panel in (0, 1):
        expected_gene[panel] = {}
        expected_pair[panel] = {}
        for view, (start, end) in P.PANEL_VIEW_RANK_SLICES[panel].items():
            genes = ranked[start:end]
            expected_gene[panel][view] = hashlib.sha256(
                genes.astype("<i4").tobytes()
            ).hexdigest()
            positions, addresses = P.select_pairs(genes, panel=panel, view=view)
            assert positions.shape == (2048, 2)
            expected_pair[panel][view] = hashlib.sha256(
                addresses.astype("<i4").tobytes()
            ).hexdigest()

    monkeypatch.setattr(P, "PANEL_GENE_SHA256", expected_gene)
    monkeypatch.setattr(P, "PANEL_PAIR_ADDRESS_SHA256", expected_pair)

    for panel in (0, 1):
        views = P.select_gene_views(common, panel)
        for view in ("Z", "X", "Y"):
            _, addresses = P.select_pairs(views[view], panel=panel, view=view)
            assert P.verify_pair_address_hash(
                addresses, panel=panel, view=view
            ) == expected_pair[panel][view]
